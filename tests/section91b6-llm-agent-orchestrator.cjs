'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const vm=require('node:vm');
const root=path.join(__dirname,'..');
const read=f=>fs.readFileSync(path.join(root,f),'utf8');
const window={};
vm.runInNewContext(read('assets/js/agent-audio-player-skill.js'),{window});
const skill=window.StonefellowAgentAudioSkill;
const catalog=[{id:'subtle-surrender',title:'Subtle Surrender'},{id:'genius-unhumankind',title:'Genius of Unhumankind'}];
const spoken='play genius of on human kind';
const verifiedAction={type:'play_track',track_id:'genius-unhumankind'};
const receipt={method:'llm_catalog',status:'verified',track_id:'genius-unhumankind',title:'Genius of Unhumankind'};
let passed=0;
const check=(name,fn)=>{fn();passed++;process.stdout.write('91B6 PASS '+name+'\n');};
check('Imperfect ASR phrase gets genuine published server-selected ID',()=>assert.equal(skill.resolvePublished(spoken,catalog,verifiedAction,receipt).action.track_id,'genius-unhumankind'));
check('Without server receipt the ASR phrase cannot arbitrarily play a song',()=>assert.equal(skill.resolvePublished(spoken,catalog,verifiedAction).action.type,'none'));
check('Stale client catalog rejects previously published server receipt',()=>assert.equal(skill.resolvePublished(spoken,[catalog[0]],verifiedAction,receipt).action.type,'none'));
check('Changed server action ID invalidates receipt',()=>assert.equal(skill.resolvePublished(spoken,catalog,{type:'play_track',track_id:'subtle-surrender'},receipt).action.type,'none'));
check('Changed track title invalidates receipt',()=>assert.equal(skill.resolvePublished(spoken,[{id:'genius-unhumankind',title:'Something Else'}],verifiedAction,receipt).action.type,'none'));
check('LLM route cannot execute arbitrary audio URLs',()=>assert.equal(skill.validate({type:'play_track',track_id:'genius-unhumankind',url:'https://unknown.invalid/audio.mp3'}).url,undefined));
check('No model/catalog change to non-song UI action',()=>assert.equal(skill.resolvePublished('open the ticket page',catalog,{type:'open_view',view:'tickets'},receipt).action.view,'tickets'));
const php=read('api/agent-runtime.php');
const agent=read('api/agent-llm-orchestrator.php');
const app=read('assets/js/app.js');
check('Conversational LLM is called before local player routing',()=>assert.ok(php.indexOf('sf_agent_orchestrator_llm($message')<php.indexOf('$explicitPlayer=sf_agent_explicit_player_route($message);')));
check('Server emits verified receipt only for authorized catalog resolution',()=>assert.match(php,/audioResolution=\['method'=>'llm_catalog','status'=>'verified'/));
check('Public JS requires fresh server receipt and actual catalog entry',()=>assert.match(app,/verifiedNamedPlayerAction\(text,j\.action,j\.audio_resolution\)/));
check('Tool descriptions are permission-filtered for Admin and fans',()=>assert.match(agent,/sf_agent_tool_inventory\(\$admin\?'admin':'fan'\)/));
check('Consequential operations remain confirmation gated in prompt',()=>assert.match(agent,/Purchase, ticket reservation, vinyl ordering/));
process.stdout.write('Section 91B6: '+passed+' LLM orchestration and audio bridge checks passed\n');
