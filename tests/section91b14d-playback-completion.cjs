'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const vm=require('node:vm');
const root=path.resolve(__dirname,'..');
const app=fs.readFileSync(path.join(root,'assets/js/app.js'),'utf8');
const from=app.indexOf('  function playbackEndedEarly(){');
const to=app.indexOf('  function play(t,',from);
assert.ok(from>=0&&to>from,'player exposes early-end integrity detector');
const ctx={st:{track:{title:'Earth Girl',duration:284}},audio:{currentTime:100,duration:100}};
vm.runInNewContext(app.slice(from,to),ctx);
assert.equal(ctx.playbackEndedEarly(),true,'truncated 100-second audio never counts as a finished 284-second song');
ctx.audio.currentTime=280;ctx.audio.duration=284;
assert.equal(ctx.playbackEndedEarly(),false,'full-length playback advances normally');
ctx.audio.currentTime=265;ctx.audio.duration=265;
assert.equal(ctx.playbackEndedEarly(),false,'small encoding-duration variations remain valid');
ctx.audio.currentTime=30;ctx.audio.duration=30;ctx.st.track.audio_publishing_mode='preview_master_split';
assert.equal(ctx.playbackEndedEarly(),false,'published preview has intentionally shorter duration');
ctx.st.track.audio_publishing_mode='preview_only';
assert.equal(ctx.playbackEndedEarly(),false,'preview-only audio remains supported');
assert.match(app,/if\(playbackEndedEarly\(\)\)\{[\s\S]*?st\.playing=false;updateFooterPlayer\(\);[\s\S]*?return;[\s\S]*?recordListen\('complete'\)/,'truncated audio is not logged complete, auto-advanced or repeated');
console.log('Section 91B14D: 6 early-end playback checks passed');
