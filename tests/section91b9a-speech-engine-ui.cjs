'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const root=path.resolve(__dirname,'..');
const read=p=>fs.readFileSync(path.join(root,p),'utf8');
let passes=0;const check=(truth,label)=>{assert.ok(truth,label);passes++;console.log('91B9A PASS:',label)};
const account=read('assets/js/account-voice-engine.js');
const admin=read('admin/assets/speech-engine-pilot.js');
const app=read('assets/js/app.js');
const gateway=read('speech-gateway/server.mjs');
check(account.includes('#dynamicCanvas .auth-module'),'Account selector mounts into actual public canvas');
check(account.includes("page.querySelector('.account-header')||page.querySelector('#profileForm')"),'Login and recovery screens cannot receive signed-in voice settings');
check(account.includes("json('api/auth.php')")&&account.includes('X-CSRF-Token'),'Account opt-in uses same-origin auth and CSRF');
check(account.includes('pilot_available')&&account.includes('disabled=true'),'Unavailable pilot is disabled');
check(account.includes('speech_engine')&&account.includes('legacy'),'Both voice engines have explicit choices');
check(admin.includes("json('ai-providers.php')")&&admin.includes('save_speech_engine'),'Existing Admin AI provider page controls pilot');
check(admin.includes("json('auth.php')")&&admin.includes('X-CSRF-Token'),'Admin pilot changes use CSRF');
check(app.includes("stonefellow.voice.replies.v1")&&app.includes('conversationBargeIn'),'Original voice controls remain intact');
check(gateway.includes("account_bridge:'disabled'")&&gateway.includes('session.sendResponse(pilotReply())'),'Gateway fails closed until authenticated bridge');
check(!gateway.includes('disableAuth: true'),'Gateway never bypasses provider JWT verification');
check(read('stonefellow-v120.php').includes('account-voice-engine.js'),'Public selector is loaded');
check(read('admin/index.php').includes('speech-engine-pilot.js'),'Admin pilot panel is loaded');
check(read('scripts/release-zip.sh').includes('"$stage/site/speech-gateway"'),'Public deployment ZIP excludes separate Node gateway source');
console.log(`Section 91B9A: ${passes} UI and fail-closed contract assertions passed`);
